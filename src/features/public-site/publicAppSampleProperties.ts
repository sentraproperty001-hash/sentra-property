export const loadPublicAppProperties = async (): Promise<{ properties: Property[]; isSampleData: boolean }> => {
  const publishedProperties = await propertyRepository.findPublishedAsync();
  if (publishedProperties.length > 0) {
    return { properties: publishedProperties, isSampleData: false };
  }

  if (!import.meta.env.DEV) {
    return { properties: [], isSampleData: false };
  }

  return {
    properties: propertyRepository.filterPublished(PUBLIC_APP_SAMPLE_PROPERTIES, {}),
    isSampleData: true,
  };
};
